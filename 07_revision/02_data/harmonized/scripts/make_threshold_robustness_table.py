#!/usr/bin/env python3
r"""Build Appendix B's threshold-robustness table.

Referee 1 asked whether the choice gap is specific to the top-10% cutoff or
survives on a broader group (they suggested the top 20% or 30%); Referee 2
asked for robustness at the top 5% and 20% so readers can see the cutoff is
not doing the work. This table answers both in one place, and is the only
exhibit reporting the top 30%.

It is a table rather than a figure on purpose: the point is that the numbers
barely move, which a reader checks by reading down a column, and it needs no
regeneration of the figure PDFs.

Reads  02_data/harmonized/figures/threshold_robustness_{by_country,pooled}.csv
Writes 02_data/harmonized/figures/table_threshold_robustness.tex

Run:  python 07_revision/02_data/harmonized/scripts/make_threshold_robustness_table.py
"""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

# Printed setting names. The harmonized data keep the key "China"; the table
# prints the coauthors' neutral label for the Ningxia data (November 2026).
DISPLAY = {"China": "Mainland China"}


def tex_num(x, spec):
    """Format a number for a LaTeX table cell with a real minus sign.

    An ASCII hyphen in text mode prints as a hyphen, which is visibly shorter
    than the minus the prose sets in math mode; $-$ gives the same glyph.
    """
    s = format(x, spec)
    return s.replace("-", "$-$", 1) if s.startswith("-") else s

FIG = Path(__file__).resolve().parents[1] / "figures"
THRESHOLDS = (5, 10, 20, 30)
# The two application measures the main text uses. `stem_admitted` is
# deliberately excluded: it is an assignment outcome, not a choice, and it is
# the one margin that does move with the threshold (see the Results footnote).
PANELS = [
    ("first", "stem_first", "Panel A. Ranks a STEM program first"),
    ("any", "stem_any", "Panel B. Ranks a STEM program anywhere on the list"),
]


def load(name: str) -> list[dict]:
    with (FIG / f"threshold_robustness_{name}.csv").open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def gaps(rows: list[dict], outcome: str, key: str) -> dict:
    out = defaultdict(dict)
    for r in rows:
        # Only the thresholds this table reports. The source file also carries
        # the top 1%, added for Figure B.I, where Greece has no group and the
        # gap column is empty; reading it here crashed the script on a value
        # the table never prints.
        if r["outcome"] == outcome and int(r["threshold"]) in THRESHOLDS:
            out[r.get(key, "Pooled")][int(r["threshold"])] = (
                float(r["gap_female_minus_male"]) * 100
            )
    return out


def main() -> int:
    by_country, pooled = load("by_country"), load("pooled")
    lines = [
        "% Generated by make_threshold_robustness_table.py -- do not edit by hand.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{The STEM choice gap at alternative performance thresholds}",
        r"\label{tab:threshold_robustness}",
        r"\footnotesize",
        r"\begin{tabular}{l" + "r" * len(THRESHOLDS) + "}",
        r"\hline\hline",
        "Setting & " + " & ".join(f"Top {t}\\%" for t in THRESHOLDS) + r" \\",
        r"\hline",
    ]

    # Rules only where they separate different kinds of row: the header, each
    # panel's pooled block, and the frame. A rule under an italic panel title
    # boxes in a heading that the italics already set apart, and a rule between
    # the panels doubles up with the space that separates them.
    for i, (_, outcome, title) in enumerate(PANELS):
        last = i == len(PANELS) - 1
        lines.append(rf"\multicolumn{{{len(THRESHOLDS) + 1}}}{{l}}{{\textit{{{title}}}}} \\")
        country = gaps(by_country, outcome, "country")
        names = sorted(country)
        for j, name in enumerate(names):
            row = " & ".join(tex_num(country[name][t], ".1f") for t in THRESHOLDS)
            # Space, not a rule, sets the pooled summary apart from the
            # settings; the italics on Pooled/Range already mark the change.
            end = r" \\[0.5em]" if j == len(names) - 1 else r" \\"
            lines.append(f"{DISPLAY.get(name, name)} & {row}" + end)
        pool = gaps(pooled, outcome, "__none__")["Pooled"]
        row = " & ".join(tex_num(pool[t], ".1f") for t in THRESHOLDS)
        spread = max(pool.values()) - min(pool.values())
        lines.append(r"\textit{Pooled} & " + row + r" \\")
        # The gap between panels is carried by this row's own leading, now that
        # no rule sits between them.
        end = r" \\" if last else r" \\[0.9em]"
        lines.append(rf"\textit{{Range}} & \multicolumn{{{len(THRESHOLDS)}}}{{r}}"
                     rf"{{{spread:.1f} percentage points}}" + end)
        if last:
            lines.append(r"\hline")

    lines += [
        r"\hline",
        r"\end{tabular}",
        r"",
        r"\vspace{6pt}",
        r"\justifying",
        r"\footnotesize",
        r"\textit{Notes:} Female-minus-male difference in the probability of "
        r"the outcome named in each panel---ranking a STEM program first "
        r"(Panel A) or anywhere on the preference list (Panel B)---in "
        r"percentage points, among students at or above each performance "
        r"threshold. Negative values indicate that women are less likely "
        r"than men to do so. \textit{Pooled} counts "
        r"all students in the ten settings together, and \textit{Range} is the "
        r"spread of the pooled gap across the four thresholds. The main text "
        r"reports the top 10\% column.",
        r"\end{table}",
    ]

    out = FIG / "table_threshold_robustness.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    for _, outcome, title in PANELS:
        pool = gaps(pooled, outcome, "__none__")["Pooled"]
        vals = [pool[t] for t in THRESHOLDS]
        print(f"  {title.split('.')[0]}: " + ", ".join(f"{v:.1f}" for v in vals)
              + f"   range {max(vals) - min(vals):.1f} pp")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
